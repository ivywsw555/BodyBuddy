export function bilibiliSearch(ex: Exercise): string {
  return `https://search.bilibili.com/all?keyword=${encodeURIComponent(`${ex.zh} 动作要领`)}`;
}

export function youtubeSearch(ex: Exercise): string {
  return `https://www.youtube.com/results?search_query=${encodeURIComponent(ex.videoQuery ?? `${ex.name} proper form`)}`;
}

export function imageUrls(ex: Exercise): string[] {
  if (!ex.img) return [];
  const base = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises';
  return [`${base}/${ex.img}/0.jpg`, `${base}/${ex.img}/1.jpg`];
}
